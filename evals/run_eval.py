"""MatchMyCV eval runner.

    uv run python -m evals.run_eval --label baseline          # all cases, real Groq calls
    uv run python -m evals.run_eval --only A1,B3 --label quick
    uv run python -m evals.run_eval --fake                    # offline harness check

Each real run writes evals/results/<date>_<label>.json and adds a row to
evals/results/summary.md. Fake runs print their scores and write nothing.
Groq's free tier allows a few thousand tokens per minute, so a full run waits on rate limits
(the client retries 429s with backoff) and takes 10-20 minutes.
"""

import argparse
import asyncio
import json
import logging
import sys
import time
from datetime import datetime
from pathlib import Path

import yaml

from app import llm
from app.config import get_settings
from app.graph import builder
from app.schemas import OptimizationReport
from evals.fake import FakeLLM
from evals.metrics import CaseResult, score_case, summarize

HERE = Path(__file__).parent
CASES = HERE / "cases.yaml"
FIXTURES = HERE / "fixtures"
RESULTS = HERE / "results"
SUMMARY = RESULTS / "summary.md"

COLUMNS = [
    ("Run", "run"),
    ("Models (large / small)", "models"),
    ("Verdict acc.", "verdict_accuracy"),
    ("Missing caught", "missing_caught"),
    ("Overclaims", "overclaims"),
    ("Underclaims", "underclaims"),
    ("Ranking", "ranking"),
    ("Score in band", "score_in_band"),
    ("Evidence grounded", "evidence_grounded"),
    ("Fabrications (cases)", "fabrications_cell"),
    ("Injection held", "injection_held"),
    ("Revised", "revision_rate"),
    ("Reqs found", "requirements_found"),
    ("p50 / max s", "latency"),
    ("Errors", "errors"),
]


def load_cases(only: list[str] | None = None) -> tuple[list[dict], list[list[str]]]:
    data = yaml.safe_load(CASES.read_text(encoding="utf-8"))
    cases = data["cases"]
    if only:
        cases = [c for c in cases if c["id"] in only]
    return cases, data.get("ranking", [])


def read_pair(case: dict) -> tuple[str, str]:
    resume = (FIXTURES / "resumes" / f"{case['resume']}.txt").read_text(encoding="utf-8")
    job = (FIXTURES / "jobs" / f"{case['job']}.txt").read_text(encoding="utf-8")
    return resume, job


async def run_case(case: dict, fake: bool) -> tuple[CaseResult, dict | None]:
    resume, job = read_pair(case)
    if fake:
        llm.structured = FakeLLM(case, resume).structured
    started = time.perf_counter()
    try:
        report = await builder.build_graph().ainvoke(
            {"resume_text": resume, "job_text": job, "revisions": 0}
        )
        report = report["report"]
    except Exception as exc:  # noqa: BLE001 - one failed case must not stop the run
        res = CaseResult(
            id=case["id"], job=case["job"], ok=False, error=f"{type(exc).__name__}: {exc}"
        )
        res.seconds = time.perf_counter() - started
        return res, None
    res = score_case(case, report, resume)
    res.seconds = round(time.perf_counter() - started, 1)
    return res, report.model_dump(mode="json")


def print_case(r: CaseResult) -> None:
    if not r.ok:
        print(f"  {r.id}  ERROR {r.error}")
        return
    right = sum(lr.correct for lr in r.labels if lr.found)
    found = sum(lr.found for lr in r.labels)
    band = f" (band {r.score_band[0]}-{r.score_band[1]})" if r.score_band else ""
    print(
        f"  {r.id}  score {r.score}{band}  verdicts {right}/{found}  "
        f"revisions {r.revisions}  fabrications {len(r.fabrications)}  {r.seconds}s"
    )
    for lr in r.labels:
        if not lr.found:
            print(f"        not found: {lr.terms}")
        elif not lr.correct:
            print(f"        {lr.requirement!r}: {lr.status}, expected {'/'.join(lr.expected)}")
    for f in r.fabrications:
        print(f"        fabricated {f['term']!r} in {f['where']}: {f['text']}")


def row(run_id: str, models: str, s: dict) -> str:
    cells = dict(s, run=run_id, models=models)
    cells["fabrications_cell"] = f"{s['fabrications']} ({s['cases_with_fabrication']})"
    cells["latency"] = f"{s['p50_s']} / {s['max_s']}"
    return "| " + " | ".join(str(cells[key]) for _, key in COLUMNS) + " |"


def append_summary(line: str) -> None:
    head = "| " + " | ".join(c for c, _ in COLUMNS) + " |"
    rule = "| " + " | ".join("---" for _ in COLUMNS) + " |"
    if not SUMMARY.exists():
        SUMMARY.write_text(
            "# Evaluation results\n\n"
            "Generated by `evals/run_eval.py` over the 11 cases in `evals/cases.yaml`. "
            "Verdict acc. = labelled requirements given an acceptable met/partial/missing verdict. "
            "Missing caught = requirements labelled missing that were judged missing. "
            "Overclaims = judged met where the label says not met. "
            "Ranking = pairs on the same job where the stronger resume scored higher. "
            "Evidence grounded = met/partial evidence quotes found verbatim in the resume. "
            "Fabrications = trap skills the final output claims (rewrites, keywords, skills to "
            "highlight, summary, CV skills), with the number of cases in brackets. "
            "Injection held = injection cases with no overclaim, no fabrication and the score in "
            "band. Revised = cases where the guard sent the plan back.\n\n"
            f"<!-- runs -->\n{head}\n{rule}\n<!-- /runs -->\n",
            encoding="utf-8",
        )
    text = SUMMARY.read_text(encoding="utf-8")
    SUMMARY.write_text(text.replace("<!-- /runs -->", f"{line}\n<!-- /runs -->"), encoding="utf-8")


def rescore(path: Path) -> int:
    """Apply the current scoring code and labels to the reports saved in a run."""
    sys.stdout.reconfigure(encoding="utf-8")
    saved = json.loads(path.read_text(encoding="utf-8"))
    cases, ranking = load_cases()
    by_id = {c["id"]: c for c in cases}
    results = []
    for old in saved["cases"]:
        report = saved["reports"].get(old["id"])
        case = by_id.get(old["id"])
        if not report or not case:
            results.append(CaseResult(**{**old, "labels": []}))
            continue
        res = score_case(case, OptimizationReport.model_validate(report), read_pair(case)[0])
        res.seconds = old["seconds"]
        results.append(res)
        print_case(res)
    injection = {c["id"] for c in cases if c.get("injection")}
    summary = summarize(results, ranking, injection)
    print("\n" + json.dumps(summary, indent=2))
    out = path.with_name(f"{path.stem}-rescored.json")
    out.write_text(
        json.dumps(
            {
                **saved,
                "run": f"{saved['run']} (rescored)",
                "summary": summary,
                "cases": [r.to_dict() for r in results],
            },
            indent=2,
            ensure_ascii=False,
        ),
        encoding="utf-8",
    )
    append_summary(row(f"{saved['run']} (rescored)", saved["models"], summary))
    print(f"\nWrote {out.relative_to(HERE.parent)} and updated {SUMMARY.relative_to(HERE.parent)}")
    return 0


async def main() -> int:
    parser = argparse.ArgumentParser(description="Run the MatchMyCV eval set.")
    parser.add_argument("--label", default="run", help="name for this run, e.g. prompt-v2")
    parser.add_argument("--only", help="comma-separated case ids")
    parser.add_argument("--fake", action="store_true", help="scripted model, no API calls")
    parser.add_argument(
        "--rescore", metavar="RESULT_JSON", help="re-score a saved run, no API calls"
    )
    parser.add_argument("-v", "--verbose", action="store_true")
    args = parser.parse_args()
    if args.rescore:
        return rescore(Path(args.rescore))

    sys.stdout.reconfigure(encoding="utf-8")
    logging.basicConfig(level=logging.INFO if args.verbose else logging.WARNING)
    settings = get_settings()
    if not args.fake and settings.missing_keys():
        print("GROQ_API_KEY is not set. Copy .env.example to .env and add it.", file=sys.stderr)
        return 2

    cases, ranking = load_cases(args.only.split(",") if args.only else None)
    models = "fake" if args.fake else f"{settings.groq_model_large} / {settings.groq_model_small}"
    print(f"{len(cases)} case(s), models: {models}, max revisions: {settings.max_revisions}")

    results, reports = [], {}
    for case in cases:
        res, report = await run_case(case, args.fake)
        results.append(res)
        reports[case["id"]] = report
        print_case(res)

    injection = {c["id"] for c in cases if c.get("injection")}
    summary = summarize(results, ranking, injection)
    print("\n" + json.dumps(summary, indent=2))
    if args.fake:
        return 0

    stamp = datetime.now()
    run_id = f"{stamp:%Y%m%d%H%M} {args.label}"
    RESULTS.mkdir(exist_ok=True)
    out = RESULTS / f"{stamp:%Y-%m-%d}_{args.label}.json"
    out.write_text(
        json.dumps(
            {
                "run": run_id,
                "models": models,
                "max_revisions": settings.max_revisions,
                "summary": summary,
                "cases": [r.to_dict() for r in results],
                "reports": reports,
            },
            indent=2,
            ensure_ascii=False,
        ),
        encoding="utf-8",
    )
    append_summary(row(run_id, models, summary))
    print(f"\nWrote {out.relative_to(HERE.parent)} and updated {SUMMARY.relative_to(HERE.parent)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(asyncio.run(main()))
